import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';

const browser=await chromium.launch({channel:'msedge',headless:true,args:['--use-angle=d3d11']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[],assets=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('response',response=>{if(response.url().includes('/synarc-kit/')&&response.url().endsWith('/kit.glb'))assets.push({url:response.url(),status:response.status()});});
 await page.goto(`${process.env.CITY_TEST_ORIGIN||'http://127.0.0.1:5173'}/city?demo=1&cityStudio=1&cityStudioTest=1${process.env.CITY_BACKEND==='webgl'?'&cityBackend=webgl':''}`);
 await page.waitForFunction(()=>Object.keys(localStorage).some(k=>k.startsWith('city-land-v1-')),null,{timeout:60000});
 await page.evaluate(async()=>{
  const {initialLandDraft,LAND_OWNER}=await import('/src/domain/cityLand.ts');
  const {studioExample}=await import('/src/domain/cityStudioExamples.ts');
  const key=Object.keys(localStorage).find(k=>k.startsWith('city-land-v1-'));
  const world=JSON.parse(localStorage.getItem(key)),plot=world.plots[0];
  plot.owner=LAND_OWNER;plot.purchaseId='browser-access';plot.revision=1;
  const draft=studioExample(initialLandDraft(plot),2,plot.size);
  draft.name='Access route test';
  draft.sculpt.volumes=[{id:'main',kind:'rectangle',operation:'add',x:0,z:0,width:12,depth:7,startFloor:0,spanFloors:3}];
  draft.sculpt.studio.assemblies=[];draft.sculpt.studio.openings=[];draft.sculpt.studio.defaults.roof='flat';
  plot.draft=draft;
  localStorage.setItem(key,JSON.stringify(world));
 });
 await page.reload();
 await page.getByRole('button',{name:'Drive mode',exact:true}).click();
 await page.getByRole('button',{name:'Visit test plot'}).click();
 await page.getByRole('region',{name:'Construction studio'}).waitFor({timeout:60000});
 await page.waitForFunction(()=>document.querySelector('canvas')?.dataset.cityStudioKit==='ready',null,{timeout:60000});
 const catalogue=await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('city-land-v1-')).map(k=>JSON.parse(localStorage.getItem(k)).plots.find(p=>p.owner)?.draft?.sculpt?.studio?.catalogue));
 assert.ok(assets.some(asset=>asset.url.includes('/synarc-kit/v3/kit.glb')&&asset.status===200),JSON.stringify({catalogue,assets}));
 const kitKeys=await page.evaluate(async()=>{const {loadStudioKit}=await import('/src/features/city/CityStudioMeshes.tsx');return [...(await loadStudioKit(3)).keys()];});
 assert.ok(kitKeys.includes('wall-full'),JSON.stringify(kitKeys.slice(0,8)));
 await page.getByRole('button',{name:'Front view'}).click();
 mkdirSync('output/playwright',{recursive:true});
 await page.screenshot({path:'output/playwright/city-studio-access.png'});
 await page.getByRole('button',{name:'Orbit view'}).click();
 await page.getByRole('button',{name:'Decorate',exact:true}).click();
 await page.getByRole('button',{name:'Stair',exact:true}).click();
 await page.getByLabel('Stair exit').getByRole('button',{name:'Balcony'}).waitFor({timeout:10000});
 await page.getByLabel('Stair exit').getByRole('button',{name:'Balcony'}).click();
 await page.getByLabel('Stair shape').getByRole('button',{name:'Switchback'}).click();
 await page.getByLabel('Stair exit').getByRole('button',{name:'Door'}).click();
 await page.waitForTimeout(200);
 const bay=await page.locator('canvas').evaluate(canvas=>JSON.parse(canvas.dataset.cityStudio).bays.filter(b=>b.floor===0&&b.side==='east').sort((a,b)=>Math.abs(a.x-innerWidth/2)-Math.abs(b.x-innerWidth/2))[0]);
 assert.ok(bay,'A ground-floor exposed bay must be available');
 await page.mouse.click(bay.x,bay.y);
 await page.waitForFunction(()=>Object.keys(localStorage).some(key=>key.startsWith('city-land-v1-')&&JSON.parse(localStorage.getItem(key)).plots.some(plot=>plot.owner&&plot.draft?.sculpt?.studio?.assemblies?.some(a=>a.kind==='stair'&&a.exit))),null,{timeout:30000});
 await page.getByRole('button',{name:'Stair 1 · storey 2'}).click();
 await page.getByRole('button',{name:'Flip direction'}).click();
 await page.getByRole('button',{name:'Apply changes'}).click();
 await page.waitForFunction(()=>Object.keys(localStorage).some(key=>key.startsWith('city-land-v1-')&&JSON.parse(localStorage.getItem(key)).plots.some(plot=>plot.owner&&plot.draft?.sculpt?.studio?.assemblies?.some(a=>a.kind==='stair'&&a.flip&&a.exit))),null,{timeout:30000});
 await page.waitForFunction(()=>!document.querySelector('.studio-preparing'),null,{timeout:30000});
 await page.screenshot({path:'output/playwright/city-studio-access-built.png'});
 await page.getByRole('button',{name:'Paint',exact:true}).click();
 await page.getByRole('button',{name:'frame',exact:true}).waitFor({timeout:10000});
 await page.getByRole('button',{name:'Stone',exact:true}).waitFor({timeout:10000});
 await page.getByRole('button',{name:'Walk around'}).click();
 await page.getByRole('button',{name:'Return to building E'}).click();
 await page.getByRole('region',{name:'Construction studio'}).waitFor({timeout:10000});
 await page.reload();
 await page.getByRole('button',{name:'Drive mode',exact:true}).click();
 await page.getByRole('button',{name:'Visit test plot'}).click();
 await page.getByRole('region',{name:'Construction studio'}).waitFor({timeout:60000});
 const saved=await page.evaluate(()=>{const key=Object.keys(localStorage).find(k=>k.startsWith('city-land-v1-'));return JSON.parse(localStorage.getItem(key)).plots.find(p=>p.owner)?.draft?.sculpt?.studio?.assemblies?.find(a=>a.kind==='stair');});
 assert.ok(saved?.exit&&saved?.exitKind==='door'&&saved?.layout==='switchback',JSON.stringify(saved));
 assert.deepEqual(errors,[]);
 console.log('Construction studio loads v3, places and reopens a fitted stair, exposes visual paint controls, and enters draft walk-through.');
}finally{await browser.close();}
