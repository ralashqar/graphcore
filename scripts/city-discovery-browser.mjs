import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const origin=process.env.CITY_TEST_ORIGIN||'http://127.0.0.1:5187';
await mkdir('output/playwright',{recursive:true});
const browser=await chromium.launch({headless:true,args:process.platform==='win32'?['--use-angle=d3d11']:[]});
const errors=[];
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 await page.goto(`${origin}/city/discover?demo=1`);
 await page.getByRole('heading',{name:'Find your next creative possibility.'}).waitFor();
 await page.getByRole('button',{name:/Make your first creative launch/}).click();
 await page.getByRole('slider').waitFor();
 await page.getByRole('slider').fill('75');
 await page.getByRole('button',{name:'Mark stop explored'}).click();
 await page.getByText('1 of 3 explored.',{exact:false}).waitFor();
 await page.getByRole('button',{name:'Next stop'}).click();
 await page.getByRole('button',{name:'Expressive',exact:true}).click();
 await page.getByRole('button',{name:'Mark stop explored'}).click();
 await page.getByRole('button',{name:'Next stop'}).click();
 await page.getByText('SHARED PAVILION EXHIBIT',{exact:true}).waitFor();
 await page.getByText('DISCOVERY PAVILION',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Mark stop explored'}).click();
 await page.getByText('3 of 3 explored.',{exact:false}).waitFor();
 await page.screenshot({path:'output/playwright/city-discovery-trail.png',fullPage:true});
 await page.reload();
 await page.getByText('3 of 3 explored.',{exact:false}).waitFor();
 await page.getByText('SHARED PAVILION EXHIBIT',{exact:true}).waitFor();
 await page.locator('canvas').waitFor();
 await page.getByText('DISCOVERY PAVILION',{exact:true}).waitFor();
 await page.evaluate(()=>document.querySelector('canvas').dispatchEvent(new Event('webglcontextlost',{cancelable:true})));
 await page.getByText('Map unavailable.',{exact:false}).waitFor();
 await page.getByRole('button',{name:'Expressive',exact:true}).click();
 await page.goto(`${origin}/city/launches/creator-friday?demo=1`);
 await page.getByRole('button',{name:'Save launch',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Fictional exhibit'}).waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'output/playwright/city-discovery-mobile.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await page.goto(`${origin}/city/business/creator-2?demo=1`);
 await page.getByText('SHARED PAVILION EXHIBIT',{exact:true}).waitFor();
 assert.deepEqual(errors,[]);
 await writeFile('output/playwright/city-discovery-results.json',JSON.stringify({errors,checks:['trail mixed paid/free navigation','comparison and guided samples','anonymous progress reload','pavilion','launch demo guard','mobile viewport','WebGL fallback','free storefront deep link']},null,2));
 console.log('Discovery browser checks passed.');
}finally{await browser.close();}
